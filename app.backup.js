const books = document.querySelector("#books");
const search = document.querySelector("#bookSearch");
let currentYear = "1";

function render(){
  const q = search.value.toLowerCase().trim();
  books.innerHTML = "";
  (resources[currentYear] || []).filter(x => x.join(" ").toLowerCase().includes(q)).forEach(x => {
    const el = document.createElement("article");
    el.className = "book";
    el.innerHTML = `<span class="tag">${x[0]}</span><h3>${x[1]}</h3><p>${x[2]}</p><a href="${x[3]}" target="_blank" rel="noopener">Open official resource →</a>`;
    books.appendChild(el);
  });
  if(!books.children.length) books.innerHTML = "<div class='notice'>No matching resource found. Try another subject.</div>";
}
document.querySelectorAll(".year").forEach(btn => btn.addEventListener("click", () => {
  document.querySelectorAll(".year").forEach(b=>b.classList.remove("active"));
  btn.classList.add("active");
  currentYear = btn.dataset.year;
  search.value = "";
  render();
}));
search.addEventListener("input", render);
render();
document.querySelector("#year").textContent = new Date().getFullYear();

